/**
 * Resolves an image key, URL, or descriptor into a high-res image URL.
 */
export function resolveImageUrl(keyOrUrl?: string | null, fallbackKey = "produce"): string {
  if (!keyOrUrl || keyOrUrl.trim() === "") {
    return CURATED_IMAGES[fallbackKey] ?? CURATED_IMAGES.general;
  }
  const clean = keyOrUrl.trim();
  if (clean.startsWith("http://") || clean.startsWith("https://") || clean.startsWith("/api/v1/media/")) {
    return clean;
  }
  const lower = clean.toLowerCase();
  if (CURATED_IMAGES[lower]) {
    return CURATED_IMAGES[lower];
  }
  return CURATED_IMAGES[fallbackKey] ?? CURATED_IMAGES.general;
}
